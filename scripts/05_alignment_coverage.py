#!/usr/bin/env python3

"""
Calculate genomic reference-position coverage from passing Sanger alignments.

Inputs:
    Coordinate-sorted BAM generated by 04_align_genomic_reads.py
    Alignment QC CSV generated by 04_align_genomic_reads.py

Outputs:
    <sample>_<gene>_<target>_Position_Coverage.csv
    <sample>_<gene>_<target>_Alignment_Details.csv

Only primary alignments passing the alignment QC filter are included.

Read depth counts aligned bases, not deletions or skipped reference
positions. Primer-direction labels are tracked separately from the
alignment strand and do not establish independent strand support.
"""

import argparse
import csv
import subprocess
from collections import defaultdict, Counter
from pathlib import Path


def read_alignment_qc(path, sample, gene, target):
    with path.open(newline="", encoding="utf-8-sig") as handle:
        rows = list(csv.DictReader(handle))

    selected = [
        row for row in rows
        if row["Sample"] == sample
        and row["Gene"] == gene
        and row["Target"] == target
        and row["Alignment_QC_flag"] == "PASS"
    ]

    if not selected:
        raise ValueError("No passing alignments found")

    ids = [row["Read_ID"] for row in selected]

    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate passing Read_ID values")

    return {row["Read_ID"]: row for row in selected}


def parse_cigar(cigar):
    import re

    operations = re.findall(r"(\d+)([MIDNSHP=X])", cigar)

    if not operations:
        raise ValueError(f"Invalid CIGAR: {cigar}")

    if "".join(f"{n}{op}" for n, op in operations) != cigar:
        raise ValueError(f"Malformed CIGAR: {cigar}")

    return [(int(n), op) for n, op in operations]


def process_alignment(fields, metadata, coverage):
    read_id = fields[0]
    flag = int(fields[1])
    chromosome = fields[2]
    start = int(fields[3])
    cigar = fields[5]

    if flag & (0x4 | 0x100 | 0x800):
        raise ValueError(f"Unexpected alignment flag for {read_id}")

    direction = metadata["Direction"]

    if direction not in {"F", "R"}:
        raise ValueError(
            f"Unrecognized primer direction for {read_id}: {direction}"
        )

    reference_position = start

    aligned_reference_bases = 0
    insertion_bases = 0
    deletion_bases = 0
    softclipped_bases = 0

    for length, operation in parse_cigar(cigar):
        if operation in {"M", "=", "X"}:
            for position in range(
                reference_position,
                reference_position + length
            ):
                coverage[(chromosome, position)].add(read_id)

            aligned_reference_bases += length
            reference_position += length

        elif operation == "I":
            insertion_bases += length

        elif operation == "D":
            deletion_bases += length
            reference_position += length

        elif operation == "N":
            reference_position += length

        elif operation == "S":
            softclipped_bases += length

        elif operation in {"H", "P"}:
            pass

    return {
        "Sample": metadata["Sample"],
        "Read_ID": read_id,
        "Gene": metadata["Gene"],
        "Target": metadata["Target"],
        "Primer_direction": direction,
        "Alignment_strand": "-" if flag & 16 else "+",
        "Start_GRCh38_1based": start,
        "End_GRCh38_1based": reference_position - 1,
        "CIGAR": cigar,
        "Aligned_reference_bases": aligned_reference_bases,
        "Insertion_bases": insertion_bases,
        "Deletion_bases": deletion_bases,
        "Softclipped_bases": softclipped_bases,
        "Alignment_QC_flag": "PASS",
    }


def main():
    parser = argparse.ArgumentParser(
        description="Calculate coverage from passing genomic Sanger reads."
    )

    parser.add_argument("--bam", required=True, type=Path)
    parser.add_argument("--alignment-qc", required=True, type=Path)
    parser.add_argument("--sample", required=True)
    parser.add_argument("--gene", required=True)
    parser.add_argument("--target", required=True)
    parser.add_argument("--output-dir", required=True, type=Path)

    args = parser.parse_args()

    bam = args.bam.expanduser().resolve()
    qc_path = args.alignment_qc.expanduser().resolve()
    output_dir = args.output_dir.expanduser().resolve()

    for path in [bam, qc_path]:
        if not path.is_file():
            parser.error(f"Missing input: {path}")

    metadata = read_alignment_qc(
        qc_path,
        args.sample,
        args.gene,
        args.target,
    )

    command = [
        "samtools",
        "view",
        "-F", "2308",
        str(bam),
    ]

    result = subprocess.run(
        command,
        check=True,
        capture_output=True,
        text=True,
    )

    coverage = defaultdict(set)
    details = []
    seen = set()

    for line in result.stdout.splitlines():
        fields = line.split("\t")
        read_id = fields[0]

        if read_id not in metadata:
            continue

        if read_id in seen:
            raise ValueError(
                f"Multiple passing primary alignments for {read_id}"
            )

        seen.add(read_id)

        details.append(
            process_alignment(
                fields,
                metadata[read_id],
                coverage,
            )
        )

    missing = set(metadata) - seen

    if missing:
        raise RuntimeError(
            f"Passing reads missing from BAM: {sorted(missing)}"
        )

    coverage_rows = []

    for (chromosome, position), read_ids in sorted(
        coverage.items()
    ):
        directions = [
            metadata[read_id]["Direction"]
            for read_id in read_ids
        ]

        forward_count = directions.count("F")
        reverse_count = directions.count("R")

        coverage_rows.append({
            "Sample": args.sample,
            "Gene": args.gene,
            "Target": args.target,
            "Chromosome": chromosome,
            "Position_GRCh38_1based": position,
            "Read_depth": len(read_ids),
            "Supporting_read_IDs": ";".join(sorted(read_ids)),
            "Forward_primer_reads": forward_count,
            "Reverse_primer_reads": reverse_count,
            "Both_primer_directions": (
                forward_count > 0 and reverse_count > 0
            ),
        })

    output_dir.mkdir(parents=True, exist_ok=True)

    coverage_path = output_dir / (
        f"{args.sample}_{args.gene}_{args.target}_Position_Coverage.csv"
    )

    details_path = output_dir / (
        f"{args.sample}_{args.gene}_{args.target}_Alignment_Details.csv"
    )

    for path, rows in [
        (coverage_path, coverage_rows),
        (details_path, details),
    ]:
        if not rows:
            raise RuntimeError(f"No output records for {path}")

        with path.open(
            "w", newline="", encoding="utf-8"
        ) as handle:
            writer = csv.DictWriter(
                handle,
                fieldnames=list(rows[0].keys()),
            )
            writer.writeheader()
            writer.writerows(rows)

    depth_counts = Counter(
        row["Read_depth"]
        for row in coverage_rows
    )

    both_directions = sum(
        row["Both_primer_directions"]
        for row in coverage_rows
    )

    print("\nGENOMIC SANGER COVERAGE")
    print("=" * 65)
    print("Sample:", args.sample)
    print("Gene:", args.gene)
    print("Target:", args.target)
    print("Passing reads:", len(details))
    print("Covered reference positions:", len(coverage_rows))

    print("\nDepth distribution:")
    for depth, count in sorted(depth_counts.items()):
        print(f"  Depth {depth}: {count} positions")

    print(
        "\nPositions with both primer labels:",
        both_directions,
    )

    print("\nSaved:")
    print(" ", coverage_path)
    print(" ", details_path)

    print("\nNo variant validation or genotype inference performed.")


if __name__ == "__main__":
    main()
