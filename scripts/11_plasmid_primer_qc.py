#!/usr/bin/env python3

"""
Summarize MAP3K6 plasmid Sanger sequencing quality by primer.

Uses the inventory and trimming summary generated by earlier scripts.

This script performs primer-level quality control only.
It does not align plasmid sequences or call variants.
"""

import argparse
import csv
import re
from collections import Counter, defaultdict
from pathlib import Path


PRIMERS = (
    [f"F{i}" for i in range(1, 7)]
    + ["M13F", "M13R"]
    + [f"R{i}" for i in range(1, 7)]
)

PRIMER_PATTERN = re.compile(
    r"(?i)MAP3K6_+plasmid_+\d+_+(M13F|M13R|F[1-6]|R[1-6])(?=_)"
)


def load_csv(path):
    with path.open(newline="", encoding="utf-8-sig") as handle:
        return list(csv.DictReader(handle))


def find_column(columns, candidates, description):
    for candidate in candidates:
        if candidate in columns:
            return candidate

    raise ValueError(
        f"Cannot identify {description}. "
        f"Available columns: {columns}"
    )


def main():
    parser = argparse.ArgumentParser(
        description="Summarize MAP3K6 plasmid primer sequencing QC."
    )

    parser.add_argument("--inventory", required=True, type=Path)
    parser.add_argument("--trim-qc", required=True, type=Path)
    parser.add_argument("--sample", required=True)
    parser.add_argument("--output-dir", required=True, type=Path)

    args = parser.parse_args()

    inventory_path = args.inventory.expanduser().resolve()
    trim_path = args.trim_qc.expanduser().resolve()
    output_dir = args.output_dir.expanduser().resolve()

    for path in [inventory_path, trim_path]:
        if not path.is_file():
            parser.error(f"Missing input: {path}")

    inventory = [
        row for row in load_csv(inventory_path)
        if row["Sample"] == args.sample
        and row["Sequencing_group"] == "PLASMID"
    ]

    trim_rows = [
        row for row in load_csv(trim_path)
        if row["Sample"] == args.sample
    ]

    if not inventory:
        parser.error("No plasmid reads found in inventory")

    if not trim_rows:
        parser.error("No trimming QC rows found")

    trim_columns = list(trim_rows[0])

    status_column = find_column(
        trim_columns,
        [
            "Trim_QC_flag",
            "Trim_QC_status",
            "Trim_status",
            "Trimmed_QC_flag",
            "QC_flag",
            "Status",
        ],
        "trimming status column",
    )

    trim_lookup = {}

    for row in trim_rows:
        read_id = row["Read_ID"]

        if read_id in trim_lookup:
            raise ValueError(f"Duplicate trimming row: {read_id}")

        trim_lookup[read_id] = row

    groups = defaultdict(list)

    for row in inventory:
        read_id = row["Read_ID"]
        filename = row["Filename"]

        match = PRIMER_PATTERN.search(filename)

        if not match:
            raise ValueError(
                f"Cannot determine MAP3K6 primer: {filename}"
            )

        primer = match.group(1).upper()

        if read_id not in trim_lookup:
            raise ValueError(
                f"Missing trimming QC for {read_id}"
            )

        groups[primer].append({
            "Read_ID": read_id,
            "Status": trim_lookup[read_id][status_column],
        })

    unexpected = set(groups) - set(PRIMERS)

    if unexpected:
        raise ValueError(
            f"Unexpected primer groups: {sorted(unexpected)}"
        )

    status_counts = Counter(
        item["Status"]
        for records in groups.values()
        for item in records
    )

    print("\nObserved trimming status values:")
    for status, count in sorted(status_counts.items()):
        print(f"  {status}: {count}")

    # Determine retained status from the actual trimming table.
    retained_values = {
        "PASS",
        "PASS_TRIMMED_QC",
        "PASS_TRIM_QC",
        "RETAINED",
        "PASS_QUALITY_TRIM",
    }

    unknown_statuses = [
        status for status in status_counts
        if status not in retained_values
        and not status.startswith("NO_")
        and not status.startswith("LOW_")
        and status not in {"FAIL", "SHORT_READ", "EXCLUDED"}
    ]

    if unknown_statuses:
        raise ValueError(
            "Unrecognized trimming statuses: "
            f"{unknown_statuses}. Review the source table "
            "before classifying reads."
        )

    output_rows = []

    for primer in PRIMERS:
        records = groups.get(primer, [])

        retained = [
            item["Read_ID"]
            for item in records
            if item["Status"] in retained_values
        ]

        excluded = [
            item["Read_ID"]
            for item in records
            if item["Status"] not in retained_values
        ]

        output_rows.append({
            "Sample": args.sample,
            "Gene": "MAP3K6",
            "Sequencing_group": "PLASMID",
            "Primer": primer,
            "Total_reads": len(records),
            "Retained_reads": len(retained),
            "Excluded_reads": len(excluded),
            "Retained_read_IDs": ";".join(sorted(retained)),
            "Excluded_read_IDs": ";".join(sorted(excluded)),
            "Analysis_scope": "PRIMER_QC_ONLY",
            "Variant_validation_status": "NOT_ASSESSED",
        })

    output_dir.mkdir(parents=True, exist_ok=True)

    output_path = (
        output_dir / f"{args.sample}_MAP3K6_Plasmid_Primer_QC.csv"
    )

    with output_path.open(
        "w", newline="", encoding="utf-8"
    ) as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=list(output_rows[0]),
        )
        writer.writeheader()
        writer.writerows(output_rows)

    total = sum(row["Total_reads"] for row in output_rows)
    retained = sum(row["Retained_reads"] for row in output_rows)
    excluded = sum(row["Excluded_reads"] for row in output_rows)

    print("\nMAP3K6 PLASMID PRIMER QC")
    print("=" * 65)
    print("Sample:", args.sample)
    print("Primer groups:", len(output_rows))
    print("Total plasmid reads:", total)
    print("Retained reads:", retained)
    print("Excluded reads:", excluded)

    print("\nPer-primer results:")
    for row in output_rows:
        print(
            f"  {row['Primer']:5s} "
            f"total={row['Total_reads']} "
            f"retained={row['Retained_reads']} "
            f"excluded={row['Excluded_reads']}"
        )

    print("\nSaved:")
    print(" ", output_path)

    print("\nPlasmid variant calling was NOT performed.")


if __name__ == "__main__":
    main()
